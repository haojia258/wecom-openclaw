/**
 * worker-dispatcher.js
 * AI Orchestrator Worker 调度器 v0.4
 *
 * 根据 assignee 生成 dispatch payload。
 * v0.4 不真实调用 AI API，只生成 dispatch payload。
 *
 * 支持：
 *   - codex (OpenAI)
 *   - workbuddy (WorkBuddy built-in)
 *   - deepseek (DeepSeek)
 *   - doubao (豆包/ByteDance)
 */

const VALID_ASSIGNEES = ['codex', 'workbuddy', 'deepseek', 'doubao'];

/**
 * AI 角色配置
 */
const ASSIGNEE_CONFIG = {
  codex: {
    name: 'Codex',
    provider: 'OpenAI',
    model: 'gpt-4o',
    capabilities: ['code_generation', 'code_review', 'patch_creation', 'refactoring'],
    dispatchHint: '将以下任务发送给 Codex (OpenAI GPT-4o)，请求代码生成/审查。',
  },
  workbuddy: {
    name: 'WorkBuddy',
    provider: 'WorkBuddy Built-in',
    model: 'claude-sonnet',
    capabilities: ['task_planning', 'ops_analysis', 'report_generation', 'orchestration'],
    dispatchHint: '将以下任务发送给 WorkBuddy，请求运营分析/报告生成。',
  },
  deepseek: {
    name: 'DeepSeek',
    provider: 'DeepSeek',
    model: 'deepseek-chat',
    capabilities: ['data_analysis', 'trend_prediction', 'anomaly_detection'],
    dispatchHint: '将以下任务发送给 DeepSeek，请求数据分析/趋势预测。',
  },
  doubao: {
    name: '豆包',
    provider: 'ByteDance',
    model: 'doubao-pro',
    capabilities: ['content_generation', 'video_script', 'creative_copy'],
    dispatchHint: '将以下任务发送给豆包，请求内容创作/视频脚本。',
  },
};

/**
 * 生成 dispatch payload
 *
 * @param {object} task - 任务对象
 * @returns {object} dispatch payload
 */
function generateDispatchPayload(task) {
  const assignee = (task.assignee || 'workbuddy').toLowerCase();

  if (!VALID_ASSIGNEES.includes(assignee)) {
    return {
      error: `Unknown assignee: ${assignee}. Valid: ${VALID_ASSIGNEES.join(', ')}`,
      assignee: null,
      payload: null,
    };
  }

  const config = ASSIGNEE_CONFIG[assignee];
  const payload = {
    assignee: assignee,
    assigneeName: config.name,
    provider: config.provider,
    model: config.model,
    taskId: task.taskId,
    branch: task.branch || '',
    patchFile: task.patchFile || '',
    forbidden: task.forbidden || [],
    acceptance: task.acceptance || '',
    instruction: buildInstruction(task, assignee, config),
    dispatchHint: config.dispatchHint,
    capabilities: config.capabilities,
    generatedAt: new Date().toISOString(),
    status: 'pending', // pending | accepted | running | done | failed
    _note: 'v0.5 — Codex/OpenAI supports real AI API call. Other workers remain mock.',
  };

  return {
    assignee: assignee,
    assigneeName: config.name,
    payload,
  };
}

/**
 * 构建指令文本
 */
function buildInstruction(task, assignee, config) {
  const lines = [
    `[AI Orchestrator v0.4 Dispatch]`,
    ``,
    `To: ${config.name} (${config.provider}, ${config.model})`,
    `Task ID: ${task.taskId}`,
    ``,
    `## User Request`,
    task.userRequest || '(no request)',
    ``,
  ];

  if (task.branch) {
    lines.push(`## Branch`, task.branch, ``);
  }
  if (task.patchFile) {
    lines.push(`## Patch File`, task.patchFile, ``);
  }
  if (task.acceptance) {
    lines.push(`## Acceptance Criteria`, task.acceptance, ``);
  }
  if (task.forbidden && task.forbidden.length > 0) {
    lines.push(`## Forbidden`, task.forbidden.join(', '), ``);
  }

  lines.push(`## Capabilities`, config.capabilities.join(', '));
  lines.push(``);
  lines.push(`---`);
  lines.push(`This dispatch was generated by AI Orchestrator Runtime Core v0.4.`);
  lines.push(`Note: This is a dispatch payload — v0.4 does not execute real AI API calls.`);

  return lines.join('\n');
}

/**
 * 列出所有支持的 assignee
 */
function listAssignees() {
  return Object.entries(ASSIGNEE_CONFIG).map(([key, cfg]) => ({
    key,
    name: cfg.name,
    provider: cfg.provider,
    model: cfg.model,
    capabilities: cfg.capabilities,
  }));
}

/**
 * 获取单个 assignee 配置
 */
function getAssigneeConfig(key) {
  return ASSIGNEE_CONFIG[key.toLowerCase()] || null;
}

module.exports = {
  generateDispatchPayload,
  listAssignees,
  getAssigneeConfig,
  VALID_ASSIGNEES,
  ASSIGNEE_CONFIG,
};
